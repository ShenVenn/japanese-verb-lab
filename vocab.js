/* ===== So sánh đáp án ===== */
const kataToHira = s => s.replace(/[\u30a1-\u30f6]/g, c => String.fromCharCode(c.charCodeAt(0) - 0x60));
const ROW = {
  'あ': 'あかがさざただなはばぱまやゃらわぁゎ',
  'い': 'いきぎしじちぢにひびぴみりぃ',
  'う': 'うくぐすずつづぬふぶぷむゆゅるぅ',
  'え': 'えけげせぜてでねへべぺめれぇ',
  'お': 'おこごそぞとどのほぼぽもよょろをぉ',
};
const vowelOf = ch => { for (const [v, set] of Object.entries(ROW)) if (ch && set.includes(ch)) return v; return ''; };

/* Chuẩn hoá để so sánh: katakana -> hiragana, bỏ khoảng trắng, "ー" -> nguyên âm kéo dài
   (コーヒー và こおひい coi như giống nhau, vì gõ romaji "koohii" ra こおひい). */
export function canon(text) {
  const t = kataToHira(String(text ?? '').normalize('NFC')).replace(/[\s\u3000・'’]/g, '');
  let out = '';
  for (const ch of t) out += ch === 'ー' ? vowelOf(out.slice(-1)) : ch;
  return out;
}

/* Mọi từ cùng nghĩa + cùng loại từ đều được chấp nhận (phòng trường hợp trùng nghĩa) */
const ALL = [...fromVocab, ...fromVerbs];
const answerMap = new Map();
for (const w of ALL) {
  const k = w.pos + '|' + w.meaning;
  if (!answerMap.has(k)) answerMap.set(k, new Set());
  answerMap.get(k).add(canon(w.reading));
}
ALL.forEach(w => { w.answers = [...answerMap.get(w.pos + '|' + w.meaning)]; });

export const buildBank = level => ALL.filter(w => level === 'all' || w.level === level);
export const isCorrect = (w, typed) => w.answers.includes(canon(typed));
